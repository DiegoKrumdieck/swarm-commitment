import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import analysis_extra as X  # noqa: E402
import analysis_lib as A  # noqa: E402
import params as P  # noqa: E402
from tools.run_check import summarize  # noqa: E402

LAB = {"main": "Haiku", "cross_family": "Luna", "frontier": "Sol"}
FIG = A.FIG


def ci(r, k):
    v, lo, hi = r.get(k), r.get(f"{k}_lo"), r.get(f"{k}_hi")
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "–"
    return f"{v:.2f} [{lo:.2f}, {hi:.2f}]"


def num(v, f="{:.2f}"):
    return "–" if v is None or (isinstance(v, float) and np.isnan(v)) else f.format(v)


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def hyp_rows(rows):
    hdr = ["model", "cell", "round 1 [95% CI]", "n (dec/ep)", "all rounds [95% CI]", "n dec", "pw / ca",
           "ended", "KM S(4)", "ended by A/B/both", "score A / B", "bench ender pw / ca"]
    out = []
    for r in rows:
        if not r.get("n_episodes"):
            continue
        out.append([LAB.get(r["model"], r["model"]), r["cell"], ci(r, "r1"), f"{r['r1_n']}/{r['n_episodes']}",
                     ci(r, "all"), r["all_n"], f"{num(r['pw_pred'], '{:.0f}')} / {num(r['ca_pred'], '{:.0f}')}",
                     num(r["ended_share"]), num(r["km_S4"]), f"{r['ended_A']}/{r['ended_B']}/{r['ended_both']}",
                     f"{num(r['score_A'], '{:.0f}')} / {num(r['score_B'], '{:.0f}')}",
                     f"{r['pw_ender'] or '–'} / {r['ca_ender'] or '–'}"])
    return md_table(hdr, out)


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    M = {m: A.load(1, m) for m in ("main", "cross_family", "frontier")}
    S = {m: A.cell_summary(*M[m]) for m in M}
    for m in S:
        S[m].to_csv(ROOT / "results" / f"cell_summary_{m}.csv", index=False)
    D2, E2 = A.load(2, "main", wording=None)
    D3, E3 = A.load(3, "main", wording=None)
    H = A.hypothesis_tables(S, E2, E3)

    # ---- exploratory ----
    ctab = {m: X.contagion_table(*M[m]) for m in ("main", "cross_family")}
    cfr = {LAB[m]: X.contagion_frame(*M[m]) for m in ("main", "cross_family")}
    X.fig6a(cfr, FIG / "fig6a_overdraw_by_round.png")
    X.fig6b({LAB[m]: ctab[m] for m in ctab}, FIG / "fig6b_contagion.png")
    hz = {m: X.horizon_tables(*M[m]) for m in M}
    X.fig7({LAB[m]: hz[m] for m in hz}, FIG / "fig7_horizon_reading.png")
    ren = X.renaming_reasoning({LAB[m]: M[m][0] for m in M})
    fm = X.freeze_modes({LAB[m]: M[m][1] for m in M})
    evp = pd.concat([X.exit_vs_punish(*M[m], LAB[m]) for m in M], ignore_index=True)

    # ---- figures 1 / 1b with both measures ----
    for m in ("main", "cross_family"):
        R1 = A.cell_rates(M[m][0])
        Ra = A.cell_rates(M[m][0], rounds="all")
        A.fig1(R1, FIG / f"fig1_overdraw_grid_{m}.png", A.MODEL_LABEL[m], R_all=Ra)
    A.fig1b({A.MODEL_LABEL[m]: A.cell_rates(M[m][0]) for m in M}, FIG / "fig1b_models.png",
            panels_all={A.MODEL_LABEL[m]: A.cell_rates(M[m][0], rounds="all") for m in M})

    H["exploratory"] = {
        "note": "Exploratory, not pre-registered.",
        "contagion": {LAB[m]: ctab[m].round(4).to_dict(orient="records") for m in ctab},
        "horizon": {LAB[m]: {"overall_end_rate_clean": hz[m]["overall_end_rate_clean"],
                             "b_continue_value_clean_median": hz[m]["b_continue_value_clean"]["median"].round(1).to_dict(),
                             "future_cost_stable_median": hz[m]["future_cost_stable"]["median"].round(1).to_dict()}
                    for m in hz},
        "renaming_reasoning": ren["table"].round(4).to_dict(orient="records"),
        "freeze_modes": fm.to_dict(orient="records"),
        "exit_vs_punishment": evp.round(4).to_dict(orient="records"),
    }
    (ROOT / "results" / "hypotheses.json").write_text(json.dumps(H, indent=1, default=str), encoding="utf-8")

    # ---- markdown ----
    L = ["# Paper numbers", "",
         "Generated by `tools/paper_numbers.py` from the main logs (pilot/smoke logs excluded). Rates are Swarm A "
         "workers' overdraw rates with 95% percentile bootstrap CIs over episodes (2,000 resamples). **Round 1** is the "
         "no-history measure (the benchmark's prediction is about round 1); **all rounds** is the pre-registered "
         "measure (share of all A worker decisions). `pw` = per_worker benchmark, `ca` = contest_aware benchmark "
         "(predicted round-1 action: 1 overdraw, 0 quota). Deal survival: share of episodes ended by a negotiator, "
         "Kaplan–Meier P(deal survives ≥ 4 rounds), who ended it, mean swarm scores (benchmark scores are in "
         "`results/benchmark.json`). Haiku and Luna: 20 episodes per cell; Sol: 15, key cells only.", ""]

    # run costs
    runs = []
    for exp, model, wording, name in [(1, "main", "A", "Exp 1, Haiku"), (2, "main", None, "Exp 2, Haiku"),
                                      (3, "main", None, "Exp 3, Haiku"), (1, "main", "B", "Wording B, Haiku"),
                                      (1, "cross_family", "A", "Exp 1 grid, Luna"), (1, "frontier", "A", "Key cells, Sol")]:
        s = summarize(exp, model, wording=wording)
        runs.append([name, s["episodes"], s["llm_calls"], f"${s['cost_usd']:.2f}", f"{s['parse_failed_rate']:.2%}",
                     f"{s['defaulted_rate']:.2%}", f"{s['refusal_rate']:.2%}", f"{s['comprehension']:.1%}"])
    total = sum(float(r[3][1:]) for r in runs)
    pilots = [("Smoke, Haiku (prompts v1)", "smoke", 1, "main"), ("Gateway re-pilot, Haiku (v2)", "smoke/gateway_v2", 1, "main"),
              ("Smoke, Luna", "smoke/luna", 1, "cross_family")]
    for name, d, exp, model in pilots:
        s = summarize(exp, model, A.LOGS / d)
        runs.append([name + " (excluded)", s["episodes"], s["llm_calls"], f"${s['cost_usd']:.2f}",
                     f"{s['parse_failed_rate']:.2%}", f"{s['defaulted_rate']:.2%}", f"{s['refusal_rate']:.2%}",
                     f"{s['comprehension']:.1%}"])
    L += ["## Runs and costs", "", md_table(["run", "episodes", "LLM calls", "cost", "parse failed", "defaulted",
                                              "refusal (any attempt)", "comprehension"], runs), "",
          f"Main data total: **${total:.2f}**. Luna refusals are OpenAI input-moderation flags on negotiator prompts; "
          "all but 4 passed on retry (the 4 defaulted to continue / no message).", ""]

    # core cross-model table
    core = []
    for (m, c, g) in A.CORE_CELLS:
        row = [f"{m} x {c}"]
        for mdl in M:
            r = A._row_out(mdl, S[mdl], m, c, g)
            row.append(f"{ci(r, 'r1')} / {ci(r, 'all')} (n={r.get('n_episodes', 0)})" if r.get("n_episodes") else "–")
        r = A._row_out("main", S["main"], m, c, g)
        row.append(f"{num(r['pw_pred'], '{:.0f}')} / {num(r['ca_pred'], '{:.0f}')}")
        core.append(row)
    L += ["## Core cross-model table (g = 10)", "", "Each entry: round 1 [CI] / all rounds [CI] (episodes).", "",
          md_table(["cell", "Haiku", "Luna", "Sol", "pw / ca"], core), ""]

    # hypotheses
    for h in ("H1", "H2", "H3", "H4", "H5", "H7", "H8"):
        L += [f"## {h}", "", H[h]["note"], ""]
        if h == "H8":
            L += ["Direction of the g = 10 → 30 change, per model:", ""]
            dr = [[LAB[m]] + list(v.values()) for m, v in H["H8"]["direction"].items()]
            L += [md_table(["model"] + list(next(iter(H["H8"]["direction"].values())).keys()), dr), ""]
            rows = []
            for (mm, cc), _ in S["main"].groupby(["mechanism", "condition"]):
                row = [f"{mm} x {cc}" + (" **[h8]**" if S["main"][(S["main"]["mechanism"] == mm) & (S["main"]["condition"] == cc)]["h8_noise_check"].any() else "")]
                for mdl in M:
                    a = S[mdl][S[mdl]["cell_id"] == f"{mm}-{cc}-g10"]
                    b = S[mdl][S[mdl]["cell_id"] == f"{mm}-{cc}-g30"]
                    row.append(f"{a.iloc[0]['r1']:.2f}→{b.iloc[0]['r1']:.2f} / {a.iloc[0]['all']:.2f}→{b.iloc[0]['all']:.2f}"
                               if len(a) and len(b) else "–")
                a = S["main"][S["main"]["cell_id"] == f"{mm}-{cc}-g10"].iloc[0]
                b = S["main"][S["main"]["cell_id"] == f"{mm}-{cc}-g30"].iloc[0]
                row.append(f"{a['pw_pred']:.0f}→{b['pw_pred']:.0f} / {a['ca_pred']:.0f}→{b['ca_pred']:.0f}")
                rows.append(row)
            L += ["Round 1 g10→g30 / all rounds g10→g30. Full per-cell rows with CIs are in "
                  "`results/cell_summary_{model}.csv`.", "",
                  md_table(["cell", "Haiku", "Luna", "Sol", "pw / ca"], rows), ""]
        else:
            L += [hyp_rows(H[h]["rows"]), ""]
        if h == "H4":
            L += ["B's freeze decisions (retaliation cells; units are per-round freeze units placed):", "",
                  md_table(list(fm.columns), [[f"{v:.1f}" if isinstance(v, float) else v for v in r] for r in fm.values.tolist()]), "",
                  "A worker reasoning that mentions changing IDs / (non-)identifiability / spread or all-worker freezes "
                  "(keyword rules in `analysis_extra.RENAMING_PATTERNS`; exploratory; samples at the end):", "",
                  md_table(["model", "condition", "action", "n", "share mentioning"],
                           [[r["model"], r["condition"], r["action"], r["n"], f"{r['mentions_ids_or_identifiability']:.2f}"]
                            for r in ren["table"].to_dict(orient="records")]), ""]
    # H6
    L += ["## H6", "", H["H6"]["note"], "", "Exp 2 (Haiku): A's proposals by condition (trials; defaulted trials excluded: "
          f"{H['H6'].get('exp2_excluded_defaulted_trials', 0)}).", ""]
    p2 = pd.DataFrame(H["H6"]["exp2_proposals"]).T.fillna(0).astype(int)
    L += [md_table(["condition"] + list(p2.columns), [[i] + list(r) for i, r in p2.iterrows()]), "",
          "B's acceptance by proposed option: " + ", ".join(f"{k} {v}" for k, v in H["H6"]["exp2_acceptance"].items()), "",
          f"Exp 3 (Haiku): outcomes {H['H6']['exp3_outcomes']}; agreed option by condition:", ""]
    p3 = pd.DataFrame(H["H6"]["exp3_agreed"]).T.fillna(0).astype(int)
    L += [md_table(["condition"] + list(p3.columns), [[i] + list(r) for i, r in p3.iterrows()]), "",
          "Benchmark choice (A's best option that B accepts, B's workers complying): "
          + "; ".join(f"{bm}: " + ", ".join(f"{k} {'/'.join(v)}" for k, v in t.items() if k.endswith("g10"))
                      for bm, t in H["H6"]["benchmark_choice"].items()), ""]

    # wording B
    DB, EB = A.load(1, "main", wording="B")
    SB = A.cell_summary(DB, EB)
    wb = []
    for g in P.G_LEVELS:
        for (m, c) in P.KEY_CELLS:
            a = A._row_out("main", S["main"], m, c, g)
            b = A._row_out("main", SB, m, c, g)
            wb.append([f"{m}-{c}-g{g}", ci(a, "r1"), ci(b, "r1"), ci(a, "all"), ci(b, "all"),
                       f"{num(a['ended_share'])} / {num(b['ended_share'])}"])
    L += ["## Wording B (Haiku, KEY_CELLS, 20 episodes each)", "",
          md_table(["cell", "round 1, wording A", "round 1, wording B", "all rounds, A", "all rounds, B",
                    "ended share A / B"], wb), ""]

    # exploratory
    L += ["## Exploratory (not pre-registered)", "", "### Contagion (turnover and infrastructure cells)", "",
          "P(overdraw in round t | any A overdraw in t−1) vs after a clean round, rounds ≥ 2, with episode-cluster "
          "bootstrap CIs; `LPM` = coefficient on the previous-round indicator in overdraw ~ prev + round + episode "
          "FE, SE clustered by episode (– where the previous-round indicator does not vary within the cell). "
          "`pays` = overdrawing raises the worker's own score this round.", ""]
    for m in ctab:
        t = ctab[m]
        L += [f"**{LAB[m]}**", "", md_table(
            ["cell", "pays", "after overdraw [CI] (n)", "after clean [CI] (n)", "LPM coef (SE, p)", "episodes"],
            [[r["cell_id"], "yes" if r["pays_now"] else "no",
              f"{num(r['p_after_overdraw'])} [{num(r['after_lo'])}, {num(r['after_hi'])}] ({r['n_after']})",
              f"{num(r['p_after_clean'])} [{num(r['clean_lo'])}, {num(r['clean_hi'])}] ({r['n_clean']})",
              "–" if np.isnan(r["lpm_prev_coef"]) else f"{r['lpm_prev_coef']:+.2f} ({r['lpm_prev_se']:.2f}, {r['lpm_prev_p']:.3f})",
              r["n_episodes"]] for r in t.to_dict(orient="records")]), ""]
    L += ["### Horizon reading", "",
          "B negotiator's `expected_value_if_continue` after a fully clean history (non-staged cells; truth = 300 = "
          "60 / (1 − δ)), median by round (n); end rate after a clean history (A and B negotiators); A workers' "
          "`expected_future_cost_if_overdraw` by round in stable cells (median; per_worker ℓ is 20–25).", ""]
    rounds = range(2, 9)
    hrow = []
    for m in hz:
        b = hz[m]["b_continue_value_clean"]
        hrow.append([LAB[m], "B continue value"] + [f"{b.loc[t, 'median']:.0f} ({int(b.loc[t, 'count'])})" if t in b.index else "–" for t in rounds])
        f = hz[m]["future_cost_stable"]
        hrow.append([LAB[m], "A future cost (stable)"] + [f"{f.loc[t, 'median']:.0f} ({int(f.loc[t, 'count'])})" if t in f.index else "–" for t in rounds])
    L += [md_table(["model", "quantity"] + [f"round {t}" for t in rounds], hrow), "",
          "End rate after a clean history (all rounds ≥ 2): " + "; ".join(
              f"{LAB[m]} A {hz[m]['overall_end_rate_clean']['A']:.1%}, B {hz[m]['overall_end_rate_clean']['B']:.1%}" for m in hz), ""]
    L += ["### Exit vs punishment (retaliation x turnover)", "",
          "B's per-round value = 60 − 2g × (A overdraws) (B is never frozen in Exp 1). At each B decision the "
          "benchmark ends iff last round's value / (1 − δ) < 150.", "",
          md_table(list(evp.columns), [[f"{v:.2f}" if isinstance(v, float) else v for v in r] for r in evp.values.tolist()]), ""]

    def samples(df, title):
        out = [f"**{title}**", ""]
        for r in df.to_dict(orient="records"):
            txt = r["reasoning"].replace("|", "/").replace("\n", " ")
            out.append(f"- [{r['model']}, {r['cell_id']}, r{r['round']}, {r['action']}] {txt}")
        return out + [""]
    L += ["### Renaming reasoning: samples for checking the keyword rules (renaming cells)", ""]
    L += samples(ren["matches"], "10 matches")
    L += samples(ren["nonmatches"], "10 non-matches")
    (ROOT / "results" / "paper_numbers.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote results/paper_numbers.md, results/hypotheses.json, figures")


if __name__ == "__main__":
    main()
